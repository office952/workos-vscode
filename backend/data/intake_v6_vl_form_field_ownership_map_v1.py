_ALLOWED_SOURCES: frozenset[str] = frozenset(
    {
        "OPERATOR",
        "ANALYZER_OBSERVED",
        "ANALYZER_PROPOSED",
        "AI_DEFAULT",
        "OWNER_DEFAULT",
        "CATALOG",
        "DERIVED",
    }
)


def resolve_source(decision: str | None, overlay: dict[str, Any]) -> FieldSource:
    overlay_source = overlay.get("source")
    if isinstance(overlay_source, str) and overlay_source in _ALLOWED_SOURCES:
        return overlay_source  # type: ignore[return-value]
    if decision and decision in _DECISION_TO_SOURCE:
        return _DECISION_TO_SOURCE[decision]
    return "OPERATOR"
