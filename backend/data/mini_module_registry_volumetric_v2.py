def _dest(
    *,
    intake: list[str] | None = None,
    pd: list[str] | None = None,
    agg: list[str] | None = None,
    cost: list[str] | None = None,
    quote: list[str] | None = None,
    order: list[str] | None = None,
    task: list[str] | None = None,
) -> OperationalDestination:
    return OperationalDestination(
        intake_source=intake or [],
        product_definition_keys=pd or [],
        product_aggregate_display=agg or [],
        cost_engine_use=cost or [],
        quote_snapshot_use=quote or [],
        order_snapshot_use=order or [],
        task_preview_use=task or [],
    )


